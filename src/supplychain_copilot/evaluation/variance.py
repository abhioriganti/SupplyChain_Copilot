"""Run-to-run variance across repeated evaluations of the same agent (backlog #5).

Inputs (no Cortex cost; reads saved results):
  data/processed/eval_v2_results.json            the latest full run (run 5)
  data/processed/eval_v2_results_<label>.json    repeat runs from `runner --yes --repeat <label>`

Reports, per case, how many runs passed, which checks failed when it didn't, and whether the tool set
changed; per run, pass count and latency. "Consistent" means passed in every run (pass^k), the stricter
measure an operator cares about, alongside the mean pass rate (pass@1).

Run:  .venv\\Scripts\\python -m supplychain_copilot.evaluation.variance repeat2 repeat3
"""

from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path
from typing import Any

from supplychain_copilot.config import PROJECT_ROOT

PROCESSED = PROJECT_ROOT / "data" / "processed"
# Routing stability is judged on the two governed tools; chart helpers (data_to_chart, server_skill)
# come and go with presentation and are reported separately.
CORE_TOOLS = {"delivery_analytics", "supplier_documents"}
REPORT = PROJECT_ROOT / "docs" / "variance_report.md"


def load_run(path: Path) -> dict[str, Any]:
    d = json.loads(path.read_text(encoding="utf-8"))
    return {"run_id": d["run_id"], "cases": {c["id"]: c for c in d["cases"]}}


def pct(values: list[float], q: float) -> float:
    s = sorted(values)
    if not s:
        return 0.0
    k = (len(s) - 1) * q
    lo, hi = int(k), min(int(k) + 1, len(s) - 1)
    return s[lo] + (s[hi] - s[lo]) * (k - lo)


def infrastructure_failure(case: dict[str, Any]) -> bool:
    """The call never reached the model (account AI credits exhausted, HTTP 403 code 399588). Such a
    trial says nothing about answer quality, so it is excluded rather than counted as a failure."""
    detail = case["checks"].get("completed", {}).get("detail", "").lower()
    return "399588" in detail or "used its included ai credits" in detail


def analyse(runs: list[dict[str, Any]]) -> dict[str, Any]:
    """Infrastructure failures are dropped per trial, so a case keeps its valid runs."""
    present = [i for i in runs[0]["cases"] if all(i in r["cases"] for r in runs)]
    valid = {
        i: [r["cases"][i] for r in runs if not infrastructure_failure(r["cases"][i])]
        for i in present
    }
    excluded_trials = sorted(
        f"{i} in {r['run_id']}"
        for i in present
        for r in runs
        if infrastructure_failure(r["cases"][i])
    )
    ids = [i for i in present if valid[i]]
    per_run = []
    for r in runs:
        ok_ids = [i for i in ids if not infrastructure_failure(r["cases"][i])]
        lat = [r["cases"][i]["latency_s"] for i in ok_ids] or [0.0]
        per_run.append(
            {
                "run_id": r["run_id"],
                "passed": sum(r["cases"][i]["passed"] for i in ok_ids),
                "scored": len(ok_ids),
                "p50": round(statistics.median(lat), 1),
                "p95": round(pct(lat, 0.95), 1),
            }
        )
    per_case = []
    for i in ids:
        cs = valid[i]
        failed_checks = sorted(
            {
                f"{k}: {v['detail'][:120]}"
                for c in cs
                if not c["passed"]
                for k, v in c["checks"].items()
                if not v["ok"]
            }
        )
        tool_sets = {tuple(t for t in c.get("tools", []) if t in CORE_TOOLS) for c in cs}
        chart_used = {"data_to_chart" in c.get("tools", []) for c in cs}
        lat = [c["latency_s"] for c in cs]
        per_case.append(
            {
                "id": i,
                "category": cs[0].get("category", ""),
                "trials": len(cs),
                "passes": sum(c["passed"] for c in cs),
                "failed_checks": failed_checks,
                "tools_stable": len(tool_sets) == 1,
                "tool_sets": sorted(tool_sets),
                "chart_varies": len(chart_used) > 1,
                "latency_spread_s": round(max(lat) - min(lat), 1),
            }
        )
    trials = sum(c["trials"] for c in per_case)
    return {
        "runs": per_run,
        "cases": per_case,
        "k": len(runs),
        "n": len(ids),
        "trials": trials,
        "excluded": excluded_trials,
        "pass_at_1": sum(c["passes"] for c in per_case) / trials if trials else 0.0,
        "pass_all_k": sum(c["passes"] == c["trials"] for c in per_case),
        "flaky": [c for c in per_case if 0 < c["passes"] < c["trials"]],
        "never": [c for c in per_case if c["passes"] == 0],
        "tools_unstable": [c for c in per_case if not c["tools_stable"]],
        "chart_varies": [c["id"] for c in per_case if c["chart_varies"]],
    }


def render(a: dict[str, Any]) -> str:
    k, n = a["k"], a["n"]
    out = [
        "# Evaluation variance across repeated runs",
        "",
        f"Same agent, same {n} cases, {k} runs (generated by `evaluation/variance.py`; review in "
        "`docs/evaluation_findings.md`).",
        "",
        "| Run | Passed | p50 latency | p95 latency |",
        "|---|---|---|---|",
    ]
    out += [
        f"| `{r['run_id']}` | {r['passed']} / {r['scored']} | {r['p50']} s | {r['p95']} s |"
        for r in a["runs"]
    ]
    out += [
        "",
        f"- **Trials excluded (failed before reaching the model: AI credits exhausted):** "
        f"{len(a['excluded'])}{' (' + '; '.join(a['excluded']) + ')' if a['excluded'] else ''}",
        f"- **Mean pass rate (pass@1):** {a['pass_at_1']:.1%} of {a['trials']} scored case runs",
        f"- **Passed in every scored run:** {a['pass_all_k']} of {n} cases",
        f"- **Flaky (passed in some runs):** {len(a['flaky'])}",
        f"- **Failed in every run:** {len(a['never'])}",
        f"- **Governed-tool routing changed between runs:** {len(a['tools_unstable'])} cases",
        f"- **Chart drawn in some runs only (presentation, not routing):** {len(a['chart_varies'])} cases"
        f"{' (' + ', '.join(a['chart_varies']) + ')' if a['chart_varies'] else ''}",
        "",
        "## Cases that did not pass every run",
        "",
    ]
    bad = a["flaky"] + a["never"]
    if not bad:
        out.append("None.")
    for c in bad:
        out.append(f"### {c['id']} ({c['category']}): {c['passes']} of {c['trials']}")
        out += [f"- {f}" for f in c["failed_checks"]]
        out.append("")
    out += ["", "## Governed-tool routing that changed between runs", ""]
    if not a["tools_unstable"]:
        out.append("None: every case used the same governed tools in every run.")
    for c in a["tools_unstable"]:
        sets = "; ".join("[" + ", ".join(t) + "]" for t in c["tool_sets"])
        out.append(
            f"- **{c['id']}** ({c['category']}, {c['passes']} of {c['trials']} passed): {sets}"
        )
    out += ["", "## Per-case latency spread (max minus min across runs)", ""]
    spreads = sorted(a["cases"], key=lambda c: -c["latency_spread_s"])[:5]
    out += [f"- {c['id']}: {c['latency_spread_s']} s" for c in spreads]
    return "\n".join(out) + "\n"


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("labels", nargs="+", help="repeat-run labels (eval_v2_results_<label>.json)")
    args = p.parse_args()
    paths = [PROCESSED / "eval_v2_results.json"] + [
        PROCESSED / f"eval_v2_results_{lbl}.json" for lbl in args.labels
    ]
    a = analyse([load_run(x) for x in paths])
    REPORT.write_text(render(a), encoding="utf-8")
    print(
        f"{a['k']} runs x {a['n']} cases: pass@1 {a['pass_at_1']:.1%}, all-runs {a['pass_all_k']}/{a['n']}, "
        f"flaky {len(a['flaky'])}, tool-unstable {len(a['tools_unstable'])}; wrote {REPORT.relative_to(PROJECT_ROOT)}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
