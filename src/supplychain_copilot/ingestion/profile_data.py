"""Profile the raw DataCo file and write docs/profiling_report.md (every number computed, none typed).

Usage:
    python -m supplychain_copilot.ingestion.profile_data
"""

from __future__ import annotations

from datetime import UTC, datetime

import numpy as np
import pandas as pd

from supplychain_copilot.config import PROJECT_ROOT
from supplychain_copilot.ingestion import schema
from supplychain_copilot.ingestion.clean_orders import RAW_CSV, read_raw, sanitize
from supplychain_copilot.ingestion.download_data import sha256_of

REPORT_PATH = PROJECT_ROOT / "docs" / "profiling_report.md"


def _md_table(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(str(v) for v in row) + " |")
    return "\n".join(lines)


def _n(x: float | int) -> str:
    return f"{x:,}" if isinstance(x, int | np.integer) else f"{x:,.4f}"


def build_report(raw: pd.DataFrame, clean: pd.DataFrame, sha: str) -> str:
    out: list[str] = []
    add = out.append
    orders = clean.drop_duplicates("order_id")
    lines_per_order = clean.groupby("order_id").size()

    add("# DataCo profiling report\n")
    add(
        f"_Generated by `python -m supplychain_copilot.ingestion.profile_data` on "
        f"{datetime.now(UTC):%Y-%m-%d %H:%M} UTC from `{RAW_CSV.name}` "
        f"(SHA-256 `{sha[:16]}…`). Every figure below comes from the actual file._\n"
    )
    add(
        "> Public historical **retail/e-commerce** sample data (DataCo, CC BY 4.0). Not Worthington data.\n"
    )

    add("## 1. File and grain\n")
    add(
        _md_table(
            pd.DataFrame(
                [
                    ("Encoding", schema.SOURCE_ENCODING + " (not UTF-8; e.g. byte 0xE1 = 'á')"),
                    ("Rows (excluding header)", _n(len(raw))),
                    ("Columns", _n(raw.shape[1])),
                    ("Exact duplicate rows", _n(int(raw.duplicated().sum()))),
                    (
                        "Duplicate rows ignoring Order Item Id",
                        _n(int(raw.drop(columns=["Order Item Id"]).duplicated().sum())),
                    ),
                    ("Distinct Order Item Id (lines)", _n(int(clean["order_item_id"].nunique()))),
                    ("Distinct Order Id (orders)", _n(int(clean["order_id"].nunique()))),
                    ("Distinct Customer Id", _n(int(clean["customer_id"].nunique()))),
                    ("Distinct products", _n(int(clean["product_id"].nunique()))),
                    (
                        "Lines per order (min / median / mean / max)",
                        f"{lines_per_order.min()} / {lines_per_order.median():.0f} / "
                        f"{lines_per_order.mean():.2f} / {lines_per_order.max()}",
                    ),
                ],
                columns=["Measure", "Value"],
            )
        )
    )
    add(
        "\n**Grain:** one row per order line. `Order Item Id` is unique on every row; an order "
        "spans several rows. Counting rows counts lines, not orders.\n"
    )

    add("## 2. Date range\n")
    months = orders["order_ts"].dt.to_period("M")
    add(
        _md_table(
            pd.DataFrame(
                [
                    ("Order timestamp min", str(clean["order_ts"].min())),
                    ("Order timestamp max", str(clean["order_ts"].max())),
                    ("Shipping timestamp min", str(clean["shipping_ts"].min())),
                    ("Shipping timestamp max", str(clean["shipping_ts"].max())),
                    ("Distinct order months", _n(int(months.nunique()))),
                    ("Unparsed dates", "0 (parse is strict; any failure aborts cleaning)"),
                ],
                columns=["Measure", "Value"],
            )
        )
    )

    add("\n## 3. Missing values (raw, empty strings)\n")
    empties = (raw == "").sum()
    empties = empties[empties > 0].sort_values(ascending=False)
    add(
        _md_table(
            pd.DataFrame(
                {
                    "Column": empties.index,
                    "Empty values": [_n(int(v)) for v in empties.values],
                    "% of rows": [f"{v / len(raw):.2%}" for v in empties.values],
                    "Handling": [
                        "dropped (column not retained)" if c in schema.DROP else "kept as NULL"
                        for c in empties.index
                    ],
                }
            )
        )
    )
    add("\nAll other source columns have no empty values.\n")

    add("## 4. Order-level vs line-level fields\n")
    add(
        "For each retained attribute: the number of orders in which the value differs across that "
        "order's lines. Zero means the attribute is order-level.\n"
    )
    candidates = [
        *schema.ORDER_LEVEL_COLUMNS,
        "department_id",
        "product_id",
        "line_profit",
        "net_sales",
    ]
    nun = clean.groupby("order_id")[candidates].nunique(dropna=False)
    add(
        _md_table(
            pd.DataFrame(
                {
                    "Attribute": candidates,
                    "Orders with >1 distinct value": [
                        _n(int((nun[c] > 1).sum())) for c in candidates
                    ],
                    "Classification": [
                        "order-level" if (nun[c] > 1).sum() == 0 else "line/product-level"
                        for c in candidates
                    ],
                }
            )
        )
    )
    add(
        "\n**Finding:** every shipping attribute (dates, actual/scheduled days, delivery status, "
        "late flag, shipping mode, destination) is identical on all lines of an order, for all "
        f"{_n(int(clean['order_id'].nunique()))} orders. This supports one shipment per order "
        "(ADR-008). `Order Profit Per Order` is **misnamed**: it varies across lines, so it is "
        "line profit. `Department Id` is a product attribute.\n"
    )

    add("## 5. Delivery status, late flag, cancellations\n")
    ct = pd.crosstab(clean["delivery_status"], clean["late_delivery_risk"]).reset_index()
    ct.columns = ["delivery_status", "late_delivery_risk=0", "late_delivery_risk=1"]
    add("Line counts:\n\n" + _md_table(ct))
    sign = np.sign(clean["days_shipping_actual"] - clean["days_shipping_scheduled"]).map(
        {-1: "actual<scheduled", 0: "actual=scheduled", 1: "actual>scheduled"}
    )
    ct2 = pd.crosstab(clean["delivery_status"], sign).reset_index()
    add("\nActual vs scheduled days (line counts):\n\n" + _md_table(ct2))
    ct3 = pd.crosstab(clean["order_status"], clean["delivery_status"]).reset_index()
    add("\nOrder status vs delivery status (line counts):\n\n" + _md_table(ct3))
    ct4 = pd.crosstab(clean["shipping_mode"], clean["days_shipping_scheduled"]).reset_index()
    ct4.columns = ["shipping_mode", *[f"scheduled={c}d" for c in ct4.columns[1:]]]
    add("\nShipping mode vs scheduled days (line counts):\n\n" + _md_table(ct4))
    by_status = orders["delivery_status"].value_counts()
    add(
        "\nOrder-level counts by delivery status (one row per order): "
        + ", ".join(f"{k}: {_n(int(v))}" for k, v in by_status.items())
        + "\n"
    )
    add(
        "\n**Findings:**\n"
        "- `late_delivery_risk = 1` if and only if `delivery_status = 'Late delivery'`.\n"
        "- For non-canceled lines, 'late' is exactly `actual days > scheduled days`.\n"
        "- `Shipping canceled` occurs exactly when `order_status` is `CANCELED` or `SUSPECTED_FRAUD`. "
        "Some canceled lines still show actual > scheduled days, so canceled shipments must be "
        "excluded from delivery KPIs (Phase 2 eligibility rule), not counted as late.\n"
        "- Scheduled days are fully determined by shipping mode.\n"
    )

    add("## 6. Measure identities (verified, within float32 rounding of 0.011)\n")
    tol = 0.011
    ident = [
        (
            "Sales = unit price × quantity",
            (clean.gross_sales - clean.unit_price * clean.quantity).abs() <= tol,
        ),
        (
            "Order Item Total = Sales − Discount",
            (clean.net_sales - (clean.gross_sales - clean.discount_amount)).abs() <= tol,
        ),
        (
            "Sales per customer = Order Item Total (duplicate column)",
            (pd.to_numeric(raw["Sales per customer"]) - clean.net_sales).abs() <= tol,
        ),
        (
            "Benefit per order = Order Profit Per Order (duplicate column)",
            (pd.to_numeric(raw["Benefit per order"]) - clean.line_profit).abs() <= tol,
        ),
        (
            "Discount ≈ Sales × discount rate",
            (clean.discount_amount - clean.gross_sales * clean.discount_rate).abs() <= tol,
        ),
        (
            "Line profit ≈ Order Item Total × profit ratio",
            (clean.line_profit - clean.net_sales * clean.profit_ratio).abs() <= tol,
        ),
    ]
    add(
        _md_table(
            pd.DataFrame(
                {
                    "Identity": [i[0] for i in ident],
                    "Share of rows holding": [f"{i[1].mean():.2%}" for i in ident],
                }
            )
        )
    )
    add(
        "\nThe last two hold only approximately: ratios are stored rounded, so they are retained "
        "as source values and never used to recompute amounts.\n"
    )

    add("## 7. Numeric ranges\n")
    num = [
        "quantity",
        "unit_price",
        "gross_sales",
        "discount_amount",
        "discount_rate",
        "net_sales",
        "line_profit",
        "profit_ratio",
        "days_shipping_actual",
        "days_shipping_scheduled",
    ]
    add(
        _md_table(
            pd.DataFrame(
                {
                    "Column": num,
                    "Min": [f"{clean[c].min():.4f}" for c in num],
                    "Max": [f"{clean[c].max():.4f}" for c in num],
                    "Negative values": [_n(int((clean[c] < 0).sum())) for c in num],
                }
            )
        )
    )
    add("\nNegative profit values are loss-making lines. They are legitimate and retained.\n")

    add("## 8. Time structure: market rotation (critical for trend questions)\n")
    pivot = (
        orders.assign(month=months.astype(str))
        .pivot_table(
            index="month", columns="market", values="order_id", aggfunc="count", fill_value=0
        )
        .reset_index()
    )
    add("Orders per month by market:\n\n" + _md_table(pivot))
    markets_per_month = (pivot.drop(columns="month") > 0).sum(axis=1)
    add(
        f"\n**Finding:** {int((markets_per_month == 1).sum())} of {len(pivot)} months contain orders "
        "from a single market only. The dataset rotates through markets over time, so **month-over-"
        "month trends are confounded with market composition**. Valid comparisons are across "
        "markets/regions over the full period, or within one market's active months. The agent "
        "must state this caveat for time-trend questions.\n"
    )
    prods = clean.groupby(clean["order_ts"].dt.to_period("M").astype(str))["product_id"].nunique()
    add(
        "\nDistinct products sold per month also drops sharply at the end: "
        + ", ".join(f"{m}: {v}" for m, v in prods.tail(6).items())
        + f" (vs {prods.iloc[0]} in {prods.index[0]}).\n"
    )

    add("## 9. Other data-quality observations\n")
    mism = clean.drop_duplicates("order_id")["dq_ship_ts_mismatch"]
    names = clean.groupby("category_name")["category_id"].unique()
    multi = {k: sorted(int(x) for x in v) for k, v in names.items() if len(v) > 1}
    ws_cols = [c for c in raw.columns if (raw[c] != raw[c].str.strip()).any()]
    mism_lines = clean[clean["dq_ship_ts_mismatch"]]
    modes = mism_lines["shipping_mode"].value_counts().to_dict()
    deltas = (
        ((mism_lines["shipping_ts"] - mism_lines["order_ts"]).dt.total_seconds() / 3600)
        .value_counts()
        .to_dict()
    )
    add(
        f"- **Ship timestamp offset:** in {_n(int(mism.sum()))} orders ({mism.mean():.2%}), "
        "`shipping date − order date` does not equal the integer `Days for shipping (real)`. "
        f"Mismatched lines by shipping mode: {modes}. Timestamp gap in hours: {deltas}. So every "
        "Same Day shipment's timestamp is order time + 12h, whatever its actual days (0 or 1). "
        "The integer field is treated as authoritative, and these rows are flagged in "
        "`dq_ship_ts_mismatch`.\n"
        f"- **Category name not unique:** {multi}. `category_id` is the key.\n"
        f"- **Whitespace:** trailing or double spaces in {', '.join(ws_cols)}. Normalised without "
        "creating or merging categories (distinct counts unchanged).\n"
        "- **Masked PII in source:** `Customer Email` and `Customer Password` contain only "
        "`XXXXXXXXX`. Both are dropped along with names, street and zipcode.\n"
        "- **No supplier identifiers or manufacturing attributes** exist in this dataset. None are "
        "fabricated.\n"
    )
    return "\n".join(out)


def main() -> int:
    raw = read_raw(RAW_CSV)
    sha = sha256_of(RAW_CSV)
    clean = sanitize(raw, RAW_CSV.name, sha)
    REPORT_PATH.write_text(build_report(raw, clean, sha), encoding="utf-8")
    print(f"Wrote {REPORT_PATH.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
