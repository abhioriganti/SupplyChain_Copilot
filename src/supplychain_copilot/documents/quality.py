"""Extraction quality checks and the generated quality report (docs/document_extraction_report.md).

  * Word provenance (hard): every word of a chunk must occur on its cited PDF pages.
  * Order fidelity (measured): share of a chunk's 5-word windows found verbatim in the page text
    stream. Low values flag layout-heavy pages (infographics, flattened tables) for review.

Usage:
    python -m supplychain_copilot.documents.quality
"""

from __future__ import annotations

import json
import re
import unicodedata
from collections import Counter
from datetime import UTC, datetime

import pandas as pd
import pymupdf

from supplychain_copilot.config import PROJECT_ROOT
from supplychain_copilot.documents.extract import FORMULA_MARKER
from supplychain_copilot.documents.pipeline import CHUNKS_PARQUET, DOCS_PARQUET, EXTRACTION_JSON
from supplychain_copilot.documents.registry import DOCUMENTS

REPORT_PATH = PROJECT_ROOT / "docs" / "document_extraction_report.md"
_ADDED_MARKERS = [
    "[Table - layout not reliably parsed; verify against source page]",
    "(continued)",
    "[Table]",
    FORMULA_MARKER,
    "Note:",
]


def _words(text: str) -> list[str]:
    return [w for w in re.findall(r"[a-z0-9]+", unicodedata.normalize("NFKC", text).lower()) if w]


def page_words() -> dict[tuple[str, int], tuple[set[str], str]]:
    """Per PDF page: (set of words, concatenated alphanumeric character stream)."""
    out: dict[tuple[str, int], tuple[set[str], str]] = {}
    for d in DOCUMENTS:
        with pymupdf.open(d.path) as pdf:
            for i, page in enumerate(pdf, start=1):
                ws = _words(page.get_text())
                out[(d.document_id, i)] = (set(ws), "".join(ws))
    return out


def _strip_markers(text: str) -> str:
    for m in _ADDED_MARKERS:
        text = text.replace(m, " ")
    return text


def chunk_word_coverage(text, document_id, start, end, words) -> tuple[float, set[str]]:
    """A chunk word is 'on the page' if it is a page word, or its characters occur contiguously in the
    page's character stream (letter-spaced display text, words split by hyphens or formula glyphs)."""
    pages = [words[(document_id, p)] for p in range(start, end + 1)]
    pool = set().union(*(p[0] for p in pages))
    stream = "".join(p[1] for p in pages)
    ws = _words(_strip_markers(text))
    missing = {w for w in ws if w not in pool and w not in stream}
    return (1 - len(missing) / max(1, len(set(ws)))), missing


def order_fidelity(text: str, page_stream: str) -> float | None:
    lines = [
        ln
        for ln in _strip_markers(text).splitlines()
        if len(ln.split()) >= 5 and ": " not in ln[:60]
    ]
    windows = []
    for ln in lines:
        w = _words(ln)
        windows += ["".join(w[i : i + 5]) for i in range(max(1, len(w) - 4))]
    if not windows:
        return None
    return sum(1 for x in windows if x in page_stream) / len(windows)


def build_report() -> str:
    chunks = pd.read_parquet(CHUNKS_PARQUET)
    docs = pd.read_parquet(DOCS_PARQUET)
    extraction = json.loads(EXTRACTION_JSON.read_text(encoding="utf-8"))
    words = page_words()
    streams = {k: v[1] for k, v in words.items()}

    cov, fid = [], []
    for r in chunks.itertuples():
        c, _ = chunk_word_coverage(r.chunk_text, r.document_id, r.page_number, r.page_end, words)
        stream = "".join(streams[(r.document_id, p)] for p in range(r.page_number, r.page_end + 1))
        cov.append(c)
        fid.append(order_fidelity(r.chunk_text, stream))
    chunks = chunks.assign(word_coverage=cov, order_fidelity=fid)

    out = [
        "# Document extraction quality report\n",
        f"_Generated by `python -m supplychain_copilot.documents.quality` on {datetime.now(UTC):%Y-%m-%d %H:%M} UTC. "
        "All figures are computed from the actual PDFs and chunks._\n",
        "> Public documents only. The Worthington supplier documents and annual report are published on the "
        "company website and SEC EDGAR. They are retrieved for an independent portfolio demo.\n",
        "## 1. Documents and provenance\n",
        "| Document | Version (evidence) | Publication date (evidence) | Pages used | Chunks | Source |",
        "|---|---|---|---|---|---|",
    ]
    for d in docs.itertuples():
        out.append(
            f"| {d.document_title} | {d.document_version} ({d.version_evidence}) | {d.publication_date} "
            f"({d.publication_date_evidence}) | {d.pages_included}/{d.page_count} | {d.chunk_count} | [link]({d.source_url}) |"
        )
    out += [
        "\nEach source file's SHA-256 is verified against `data/manifest.json` before parsing.\n",
        "## 2. Excluded pages (logged, never cited)\n",
    ]
    for d in docs.itertuples():
        excl = json.loads(d.pages_excluded_json)
        if not excl:
            continue
        ranges: dict[str, list[int]] = {}
        for p, reason in excl.items():
            ranges.setdefault(reason, []).append(int(p))
        for reason, ps in ranges.items():
            out.append(f"- **{d.document_title}**, PDF p.{min(ps)}–{max(ps)}: {reason}")

    out += [
        "\n## 3. Chunk statistics\n",
        "| Document | Chunks | Tokens min / median / max | With tables | With overlap |",
        "|---|---|---|---|---|",
    ]
    for doc_id, g in chunks.groupby("document_id", sort=False):
        out.append(
            f"| {doc_id} | {len(g)} | {g.token_estimate.min()} / {int(g.token_estimate.median())} / {g.token_estimate.max()} "
            f"| {int(g.contains_table.sum())} | {int(g.overlap_prefix.sum())} |"
        )
    out.append(
        "\nToken counts are estimates (words × 1.33). Target 350–600; small chunks are whole short sections.\n"
    )

    out += [
        "## 4. Provenance and order fidelity\n",
        f"- **Word provenance:** {sum(1 for c in cov if c == 1.0)} of {len(cov)} chunks have 100% of their words on the "
        "cited PDF pages (pytest asserts this for every chunk).",
        f"- **Order fidelity** (share of 5-word windows found verbatim in the PDF text stream): median "
        f"{pd.Series([f for f in fid if f is not None]).median():.2f}. Chunks below 0.9 are listed for review; they "
        "come from layout-heavy pages where visual order differs from the PDF text stream.\n",
        "| Chunk | Section | PDF pages | Order fidelity |",
        "|---|---|---|---|",
    ]
    low = chunks[chunks.order_fidelity.notna() & (chunks.order_fidelity < 0.9)].sort_values(
        "order_fidelity"
    )
    for r in low.itertuples():
        out.append(
            f"| `{r.chunk_id}` | {r.section_title[:70]} | {r.page_number}–{r.page_end} | {r.order_fidelity:.2f} |"
        )
    if low.empty:
        out.append("| (none) | | | |")

    out += [
        "\n## 5. Page-level flags (manual review list)\n",
        "| Document | PDF page | Flag | Meaning |",
        "|---|---|---|---|",
    ]
    meaning = {
        "section_divider": "Divider slide with a section title only; no chunk produced",
        "image_only_content_not_extracted": "Content is an image (form/diagram); **not extracted, no OCR**",
        "formula_replaced": "A formula in math glyphs was replaced by an explicit marker",
        "table_low_confidence": "Table with nested headers; raw rows kept with a 'verify against source page' marker",
    }
    flag_counts: Counter[str] = Counter()
    for doc_id, v in extraction.items():
        for p in v["pages"]:
            for f in p["flags"]:
                flag_counts[f] += 1
                out.append(f"| {doc_id} | {p['pdf_page']} | `{f}` | {meaning.get(f, f)} |")
    tables_kept = sum(p["tables_kept"] for v in extraction.values() for p in v["pages"])
    tables_rej = sum(p["tables_rejected"] for v in extraction.values() for p in v["pages"])
    out.append(
        f"\nTable detections: **{tables_kept} kept**, **{tables_rej} rejected** (full-page slide frames, sparse or "
        "prose-like detections).\n"
    )

    out += [
        "## 6. Manually inspected chunks\n",
        "Representative chunks checked against the source PDF pages during development. Full text is shown so "
        "the reader can verify it.\n",
    ]
    picks = [
        ("Corrective action timeframes (table)", chunks.chunk_text.str.contains("14 working days")),
        (
            "Supplier scorecard weights (merged-header table)",
            chunks.chunk_text.str.contains("Quality - Quality PPM"),
        ),
        (
            "Code of Conduct: responsible supply chain",
            chunks.section_title.str.contains("Responsible Supply Chain"),
        ),
        (
            "10-K risk factor: raw materials",
            chunks.section_title.str.contains("Raw Material Pricing and Availability"),
        ),
        (
            "10-K risk factor: customers and suppliers",
            chunks.section_title.str.contains("Customers and Suppliers"),
        ),
    ]
    for label, mask in picks:
        sub = chunks[mask]
        if sub.empty:
            out.append(f"### {label}\n_Not found._\n")
            continue
        r = sub.iloc[0]
        out.append(
            f"### {label}\n`{r.chunk_id}` · {r.document_title} · **{r.section_title}** · PDF p.{r.page_number}"
            f"{'–' + str(r.page_end) if r.page_end != r.page_number else ''}"
            f"{' (printed p.' + r.printed_page_start + ')' if r.printed_page_start and r.printed_page_start != str(r.page_number) else ''}"
            f" · {r.token_estimate} tokens\n\n```text\n{r.chunk_text}\n```\n"
        )

    out += [
        "## 7. Known limitations\n",
        "- Image-only content (the PCN tag form on SQAM p.39 and a diagram on p.16) is not extracted; no OCR is used.",
        "- MD&A financial tables in the annual report are flattened to a line of numbers. The narrative text next to "
        "them restates the key figures, and numeric analysis belongs in structured data, not document retrieval.",
        "- Two nested-header tables are kept as raw rows and marked low-confidence (SQAM p.40, AR p.45).",
        "- Superscript footnote markers are attached to values (e.g. '2 working days1'); the footnote text is kept as a Note.",
        "- Infographic pages (annual report p.1–7) have lower order fidelity; their words are verified on-page.",
        "- Token counts are estimates; Cortex Search applies its own tokenizer at indexing time.",
    ]
    return "\n".join(out) + "\n"


def main() -> int:
    REPORT_PATH.write_text(build_report(), encoding="utf-8")
    print(f"Wrote {REPORT_PATH.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
